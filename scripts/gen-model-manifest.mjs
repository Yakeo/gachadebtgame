#!/usr/bin/env node
// Battle models need the same cache protection as story portraits: replacing a
// public PNG must change its URL, not leave the previous cutout in a CDN cache.
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const modelsDir = join(root, "public", "images");
export const modelManifestPath = join(root, "src", "lib", "model-manifest.ts");
export function modelManifest() {
  return Object.fromEntries(readdirSync(modelsDir)
    .filter(name => /^splash-.+\.png$/.test(name)).sort()
    .map(name => [`/images/${name}`, createHash("sha256").update(readFileSync(join(modelsDir, name))).digest("hex").slice(0, 8)]));
}
export function writeModelManifest() {
  const hashes = modelManifest();
  const content = `// GENERATED by scripts/gen-model-manifest.mjs; refreshed on every build.\n// Hashes change the URL whenever a battle sprite changes.\nexport const modelHashes: Record<string, string> = {\n${Object.entries(hashes).map(([path, hash]) => `  ${JSON.stringify(path)}: ${JSON.stringify(hash)},`).join("\n")}\n};\n`;
  let previous = "";
  try { previous = readFileSync(modelManifestPath, "utf8"); } catch { /* First generation. */ }
  if (content !== previous) writeFileSync(modelManifestPath, content);
  return Object.keys(hashes).length;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  console.log(`battle model manifest current (${writeModelManifest()} sprites)`);
}
